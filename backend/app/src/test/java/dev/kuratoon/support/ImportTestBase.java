package dev.kuratoon.support;

import static org.assertj.core.api.Assertions.assertThat;

import dev.kuratoon.image.RequiresVips;
import dev.kuratoon.ingestion.ImportJob;
import dev.kuratoon.ingestion.ImportJobRepository;
import dev.kuratoon.ingestion.ImportRecovery;
import dev.kuratoon.ingestion.ImportScanner;
import dev.kuratoon.ingestion.ImportStatus;
import dev.kuratoon.ingestion.ImportWorker;
import dev.kuratoon.ingestion.JobDetail;
import dev.kuratoon.ingestion.LibraryPaths;
import dev.kuratoon.ingestion.SidecarService;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;
import java.util.List;
import java.util.UUID;
import java.util.function.UnaryOperator;
import java.util.stream.Stream;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.transaction.support.TransactionTemplate;
import org.springframework.util.FileSystemUtils;

/**
 * Ingestion integration tests: copies cases from {@code fixtures/import} (generated by
 * {@code fixtures/generate/generate.py}) into the test import folder and drives the scanner,
 * worker and recovery directly.
 */
public abstract class ImportTestBase extends ApiTestBase {

    /** From the app module (the test working directory). */
    public static final Path FIXTURES = Path.of("../../fixtures/import").toAbsolutePath().normalize();

    /** A complete manifest (metadata without a plugin) for {@code series-basic}'s URL. */
    public static final String BASIC_COMPLETE = """
            kuratoon: 1
            kind: manifest
            url: http://fake-manga.test/series/basic
            title: Basic Series
            type: manga
            authors: [ "Basic Author" ]
            """;

    @Autowired
    protected ImportScanner scanner;

    @Autowired
    protected ImportWorker worker;

    @Autowired
    protected ImportRecovery recovery;

    @Autowired
    protected ImportJobRepository jobs;

    @Autowired
    protected LibraryPaths paths;

    @Autowired
    protected SidecarService sidecars;

    @Autowired
    protected TransactionTemplate tx;

    /** Copies a fixture case into /import under {@code folderName}. */
    protected Path copyFixture(String fixture, String folderName) {
        Path from = FIXTURES.resolve(fixture);
        assertThat(from).as("fixture %s", fixture).isDirectory();
        try (Stream<Path> files = Files.walk(from)) {
            boolean hasImages = files.anyMatch(p -> p.toString().matches("(?i).*\\.(jpg|jpeg|png|webp)$"));
            assertThat(hasImages)
                    .as("fixture images missing in %s: run python fixtures/generate/generate.py", from)
                    .isTrue();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        Path to = TestFolders.IMPORT.resolve(folderName);
        try {
            FileSystemUtils.copyRecursively(from, to);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        return to;
    }

    protected Path copyFixture(String fixture) {
        return copyFixture(fixture, fixture);
    }

    protected void writeManifest(Path folder, String yaml) {
        try {
            Files.writeString(folder.resolve("kuratoon.yml"), yaml, StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /** Polls until the folder is stable and queued (two scans across the stability window). */
    protected ImportJob queue(String folderName) {
        scanner.scanOnce();
        clock.advance(Duration.ofSeconds(61));
        List<String> queued = scanner.scanOnce();
        assertThat(queued).as("queued folders").contains(folderName);
        return tx.execute(s -> jobs.findAll().stream()
                .filter(j -> j.getSourceFolder().equals(folderName) && j.getFinishedAt() == null)
                .findFirst()
                .orElseThrow());
    }

    /** Queues the folder and runs every queued job. Returns the folder's job, reloaded. */
    protected ImportJob importFolder(String folderName) {
        ImportJob job = queue(folderName);
        worker.processAll();
        return reload(job.getId());
    }

    protected ImportJob reload(UUID jobId) {
        return tx.execute(s -> jobs.findById(jobId).orElseThrow());
    }

    /** Applies admin decisions directly (the admin API is tested separately) and re-queues. */
    protected ImportJob decideAndRetry(UUID jobId, UnaryOperator<JobDetail.Decisions> decide) {
        tx.executeWithoutResult(s -> {
            ImportJob job = jobs.findById(jobId).orElseThrow();
            job.setDetail(job.detail().withDecisions(decide.apply(job.detail().decisions())));
            job.moveTo(ImportStatus.QUEUED, null, clock.instant());
        });
        worker.processAll();
        return reload(jobId);
    }

    protected Path mediaDir(UUID mediaId) {
        return paths.mediaDir(mediaId);
    }

    protected static boolean vipsAvailable() {
        return RequiresVips.Condition.available();
    }

    protected static List<String> listNames(Path dir) {
        if (!Files.isDirectory(dir)) {
            return List.of();
        }
        try (Stream<Path> s = Files.list(dir)) {
            return s.map(p -> p.getFileName().toString()).sorted().toList();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
